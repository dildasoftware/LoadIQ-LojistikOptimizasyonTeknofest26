print(f"Arac tipleri: {sorted(pl['Arac Tipi'].unique())}")
print(f"NaN         : {pl.isnull().sum().sum()}")
print(f"Kiralik     : {pl[pl['Arac Tipi'].str.startswith('Kiralik')]['Maliyet'].sum():,.2f} TL")
print(f"Spot        : {pl[pl['Arac Tipi'].str.startswith('Spot')]['Maliyet'].sum():,.2f} TL")
