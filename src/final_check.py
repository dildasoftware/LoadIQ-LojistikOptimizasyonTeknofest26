import pandas as pd

fc = pd.read_excel("outputs/Tahminlenen_Talep.xlsx")
pl = pd.read_excel("outputs/Arac_Planlama.xlsx", sheet_name="Arac Planlama")
oz = pd.read_excel("outputs/Arac_Planlama.xlsx", sheet_name="Ozet")

print("=== TAHMINLENEN_TALEP.XLSX ===")
print(f"Boyut       : {fc.shape}")
print(f"Sutunlar    : {fc.columns.tolist()}")
print(f"Tarih aralik: {fc['Tarih'].min().date()} - {fc['Tarih'].max().date()}")
print(f"Guzergah    : {fc[['Cikis TM','Varis TM']].drop_duplicates().shape[0]}")
print(f"NaN         : {fc.isnull().sum().sum()}")
print(f"Toplam desi : {fc['Tahmin Edilen Desi'].sum():,.0f}")
print()
print("Ilk 5 satir:")
print(fc.head(5).to_string(index=False))

print()
print("=== ARAC_PLANLAMA.XLSX — ANA SAYFA ===")
